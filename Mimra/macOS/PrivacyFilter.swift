// Mimra — Privacy Pre-Filter
// Safeguards user clipboard data by strictly evaluating pasteboard metadata
// BEFORE reading or extracting any payload bytes into memory or RustCore.
// Linked Features: F-008, F-009, F-010, F-014, F-026
// Test IDs: T-PRIV-01, T-PRIV-02, T-PRIV-03, T-PRIV-04, T-PRIV-06
// ==============================================================================

import AppKit
import Foundation
import os.log

private let logger = Logger(subsystem: "com.mimra.app", category: "PrivacyFilter")

/// Descriptive explanation for why a clipboard event was rejected.
public enum DropReason: Equatable, Sendable, CustomStringConvertible {
    case paused
    case ignoreNextCopy
    case concealedMarker(String)
    case ignoredSourceApp(String)
    case ignoredType(String)
    case universalClipboard
    case emptyPasteboard
    case noSupportedTypes

    public var description: String {
        switch self {
        case .paused:
            return "Clipboard capture is paused by user."
        case .ignoreNextCopy:
            return "Ignored next copy triggered by user."
        case .concealedMarker(let marker):
            return "Sensitive/concealed marker detected: \(marker)"
        case .ignoredSourceApp(let bundleId):
            return "Source application is on the ignore list: \(bundleId)"
        case .ignoredType(let uti):
            return "Type is on the user ignored UTIs list: \(uti)"
        case .universalClipboard:
            return "Remote Universal Clipboard payload ignored per user preferences."
        case .emptyPasteboard:
            return "Pasteboard contains no items or types."
        case .noSupportedTypes:
            return "Pasteboard items contain no allowlisted representations."
        }
    }
}

/// Model representing an excluded application by bundle identity, display name, and optional binary path (F-010, T-PRIV-03).
public struct IgnoredApplication: Codable, Equatable, Hashable, Identifiable, Sendable {
    public var id: String { bundleId }
    public let bundleId: String
    public let name: String
    public let path: String?

    public init(bundleId: String, name: String, path: String? = nil) {
        self.bundleId = bundleId
        self.name = name
        self.path = path
    }
}

/// Evaluation result from the privacy filter.
public enum FilterDecision: Equatable, Sendable {
    case capture
    case drop(DropReason)
}

/// Thread-safe privacy filter that validates pasteboard metadata.
public final class PrivacyFilter: @unchecked Sendable {
    private let lock = NSLock()

    // State machine
    private var _isPaused: Bool = false
    private var _ignoreNextCopy: Bool = false
    private var _ignoreUniversalClipboard: Bool = false

    // Configurable ignore sets
    private var _ignoredApplications: [IgnoredApplication] = []
    private var _ignoredAppBundleIds: Set<String> = []
    private var _ignoredAppPaths: Set<String> = []
    private var _customIgnoredUtis: Set<String> = []

    // Format enablement configuration (F-013, F-015)
    private var _typeConfiguration: ClipboardTypeConfiguration = ClipboardTypeConfiguration()

    // Mandatory sensitive markers that MUST ALWAYS be dropped (F-008)
    public static let mandatoryConcealedMarkers: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.AutoGeneratedType",
        "org.nspasteboard.TransientType",
        "com.agilebits.onepassword",
        "com.bitwarden.desktop",
        "com.8bit.bitwarden",
        "org.keepassxc.keepassxc",
        "net.antelle.keeweb",
        "de.strongbox",
        "com.lastpass.LastPass",
        "com.enpass.Enpass",
        "com.nordpass.NordPass",
        "com.dashlane.dashlane",
        "com.roboform.mac",
    ]

    public static let universalClipboardUti = "com.apple.is-remote-clipboard"

    public init(typeConfiguration: ClipboardTypeConfiguration = ClipboardTypeConfiguration()) {
        self._typeConfiguration = typeConfiguration
    }

    // MARK: - State Configuration

    public var typeConfiguration: ClipboardTypeConfiguration {
        get {
            lock.lock()
            defer { lock.unlock() }
            return _typeConfiguration
        }
        set {
            lock.lock()
            defer { lock.unlock() }
            _typeConfiguration = newValue
            logger.info("PrivacyFilter typeConfiguration updated.")
        }
    }

    public var isPaused: Bool {
        get {
            lock.lock()
            defer { lock.unlock() }
            return _isPaused
        }
        set {
            lock.lock()
            defer { lock.unlock() }
            _isPaused = newValue
            logger.info("PrivacyFilter isPaused state updated: \(newValue, privacy: .public)")
        }
    }

    public var ignoreNextCopy: Bool {
        get {
            lock.lock()
            defer { lock.unlock() }
            return _ignoreNextCopy
        }
        set {
            lock.lock()
            defer { lock.unlock() }
            _ignoreNextCopy = newValue
            logger.info("PrivacyFilter ignoreNextCopy armed: \(newValue, privacy: .public)")
        }
    }

    public var ignoreUniversalClipboard: Bool {
        get {
            lock.lock()
            defer { lock.unlock() }
            return _ignoreUniversalClipboard
        }
        set {
            lock.lock()
            defer { lock.unlock() }
            _ignoreUniversalClipboard = newValue
        }
    }

    public var ignoredApplications: [IgnoredApplication] {
        get {
            lock.lock()
            defer { lock.unlock() }
            return _ignoredApplications
        }
        set {
            lock.lock()
            defer { lock.unlock() }
            _ignoredApplications = newValue
            _ignoredAppBundleIds = Set(newValue.map(\.bundleId))
            _ignoredAppPaths = Set(newValue.compactMap(\.path))
        }
    }

    public var ignoredAppBundleIds: Set<String> {
        get {
            lock.lock()
            defer { lock.unlock() }
            return _ignoredAppBundleIds
        }
        set {
            lock.lock()
            defer { lock.unlock() }
            _ignoredAppBundleIds = newValue
        }
    }

    public var ignoredAppPaths: Set<String> {
        get {
            lock.lock()
            defer { lock.unlock() }
            return _ignoredAppPaths
        }
        set {
            lock.lock()
            defer { lock.unlock() }
            _ignoredAppPaths = newValue
        }
    }

    public var customIgnoredUtis: Set<String> {
        get {
            lock.lock()
            defer { lock.unlock() }
            return _customIgnoredUtis
        }
        set {
            lock.lock()
            defer { lock.unlock() }
            _customIgnoredUtis = newValue
        }
    }

    private func matchesCustomIgnoredUti(_ uti: String) -> Bool {
        for pattern in _customIgnoredUtis {
            if pattern.hasSuffix("*") {
                let prefix = String(pattern.dropLast())
                if uti.lowercased().hasPrefix(prefix.lowercased()) {
                    return true
                }
            } else if uti.caseInsensitiveCompare(pattern) == .orderedSame {
                return true
            }
        }
        return false
    }

    // MARK: - Filter Evaluation

    /// Evaluates pasteboard metadata to decide if the clipboard event should be captured.
    /// CRITICAL: This method inspects ONLY types and source app metadata, NOT byte contents!
    public func shouldCapture(
        pasteboard: NSPasteboard,
        sourceBundleId: String?,
        sourcePath: String? = nil
    ) -> FilterDecision {
        lock.lock()
        defer { lock.unlock() }

        // 1. Check paused state
        if _isPaused {
            return .drop(.paused)
        }

        // 2. Check ignore-next-copy single-shot flag
        if _ignoreNextCopy {
            _ignoreNextCopy = false
            logger.info("IgnoreNextCopy triggered and disarmed.")
            return .drop(.ignoreNextCopy)
        }

        // 3. Check source application exclusion (F-010, T-PRIV-03)
        if let bundleId = sourceBundleId {
            if _ignoredAppBundleIds.contains(bundleId) || _ignoredAppPaths.contains(bundleId) {
                return .drop(.ignoredSourceApp(bundleId))
            }
        }
        if let path = sourcePath, _ignoredAppPaths.contains(path) {
            return .drop(.ignoredSourceApp(path))
        }

        // 4. Check for empty pasteboard
        guard let pbTypes = pasteboard.types, !pbTypes.isEmpty else {
            return .drop(.emptyPasteboard)
        }

        let typeStrings = Set(pbTypes.map(\.rawValue))

        // 5. Check Universal Clipboard marker if configured (F-014)
        if _ignoreUniversalClipboard && typeStrings.contains(Self.universalClipboardUti) {
            return .drop(.universalClipboard)
        }

        // 6. Check top-level mandatory concealed markers (F-008)
        for marker in Self.mandatoryConcealedMarkers {
            if typeStrings.contains(marker) {
                return .drop(.concealedMarker(marker))
            }
        }

        // 7. Check user-defined custom ignored UTIs (F-009, T-PRIV-02)
        for customUti in typeStrings {
            if matchesCustomIgnoredUti(customUti) {
                return .drop(.ignoredType(customUti))
            }
        }

        // 8. Check individual items' types for concealed markers or custom ignored UTIs
        if let items = pasteboard.pasteboardItems {
            for item in items {
                let itemTypes = Set(item.types.map(\.rawValue))
                for marker in Self.mandatoryConcealedMarkers {
                    if itemTypes.contains(marker) {
                        return .drop(.concealedMarker(marker))
                    }
                }
                for customUti in itemTypes {
                    if matchesCustomIgnoredUti(customUti) {
                        return .drop(.ignoredType(customUti))
                    }
                }
            }
        }

        // 9. Check if pasteboard contains at least one enabled supported format (F-013, F-015, T-TYPE-05)
        var allRawTypes = typeStrings
        if let items = pasteboard.pasteboardItems {
            for item in items {
                for t in item.types {
                    allRawTypes.insert(t.rawValue)
                }
            }
        }

        if !_typeConfiguration.hasAnyEnabledType(in: allRawTypes) {
            return .drop(.noSupportedTypes)
        }

        return .capture
    }
}
